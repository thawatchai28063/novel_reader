REGEX_REPLACEMENTS = [
    (re.compile(r"\?([^?\n]{1,80})\?"), r"“\1”"),
    (re.compile(r"([่้๊๋])\1+"), r"\1"),
    (re.compile(r"\s+([,.;:!?])"), r"\1"),
    (re.compile(r"([ก-๙])\s+ๆ"), r"\1 ๆ"),
    (re.compile(r"\n{3,}"), "\n\n"),
]


def fix_text(text: str) -> str:
    fixed = text
    for old, new in PHRASE_REPLACEMENTS:
        fixed = fixed.replace(old, new)
    for pattern, replacement in REGEX_REPLACEMENTS:
        fixed = pattern.sub(replacement, fixed)
    return fixed.strip()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default=str(DEFAULT_JSON))
    parser.add_argument("--output", default=str(ROOT / "ocr_work" / "chapters_ocr_fixed.json"))
    args = parser.parse_args()

    payload = json.loads(Path(args.input).read_text(encoding="utf-8"))
    changed = 0
    for chapter in payload["chapters"]:
        old_title = chapter["title"]
        old_content = chapter["content"]
        chapter["title"] = fix_text(old_title)
        chapter["content"] = fix_text(old_content)
        if chapter["title"] != old_title or chapter["content"] != old_content:
            changed += 1

    payload["source_name"] = f"{payload.get('source_name', 'OCR')} + Thai OCR fixes"
    out = Path(args.output)
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote={out} changed_chapters={changed}")
    return 0


